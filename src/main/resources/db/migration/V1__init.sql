CREATE SEQUENCE IF NOT EXISTS competition_id_seq START WITH 1 INCREMENT BY 1;

CREATE TABLE award
(
    id          INTEGER      NOT NULL,
    award_year  SMALLINT     NOT NULL,
    award_title VARCHAR(255) NOT NULL,
    winner_id   INTEGER,
    CONSTRAINT pk_award PRIMARY KEY (id)
);

CREATE TABLE competition
(
    id                BIGINT NOT NULL,
    title             VARCHAR(255),
    competition_level SMALLINT,
    referee_id        INTEGER,
    first_player_id   INTEGER,
    second_player_id  INTEGER,
    city              VARCHAR(255),
    stadium           VARCHAR(255),
    CONSTRAINT pk_competition PRIMARY KEY (id)
);

CREATE TABLE license
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    license_num VARCHAR(255),
    serial_num  INTEGER,
    descr       VARCHAR(255),
    CONSTRAINT pk_license PRIMARY KEY (id)
);

CREATE TABLE player
(
    id        INTEGER NOT NULL,
    full_name VARCHAR(255),
    rating    INTEGER,
    CONSTRAINT pk_player PRIMARY KEY (id)
);

CREATE TABLE player_sport_school
(
    player_id       INTEGER      NOT NULL,
    sport_school_id VARCHAR(255) NOT NULL,
    CONSTRAINT pk_playersportschool PRIMARY KEY (player_id, sport_school_id)
);

CREATE TABLE referee
(
    id         INTEGER NOT NULL,
    full_name  VARCHAR(255),
    license_id BIGINT,
    CONSTRAINT pk_referee PRIMARY KEY (id)
);

CREATE TABLE sport_school
(
    id    VARCHAR(255) NOT NULL,
    title VARCHAR(255),
    CONSTRAINT pk_sportschool PRIMARY KEY (id)
);

CREATE TABLE sport_school_rating
(
    school_id VARCHAR(255) NOT NULL,
    rating    INTEGER      NOT NULL
);

