CREATE TABLE award(
    id        INTEGER      NOT NULL,
    year_     SMALLINT     NOT NULL,
    title     VARCHAR(255) NOT NULL,
    winner_id INTEGER,
    CONSTRAINT pk_award PRIMARY KEY (id)
);

CREATE TABLE competition(
    id                BIGINT NOT NULL,
    title             VARCHAR(255),
    competition_level SMALLINT CHECK (competition_level BETWEEN 0 AND 3),
    referee_id        INTEGER,
    first_player_id   INTEGER,
    second_player_id  INTEGER,
    city              VARCHAR(255),
    stadium           VARCHAR(255),
    CONSTRAINT pk_competition PRIMARY KEY (id)
);

CREATE TABLE license(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    license_number VARCHAR(255),
    sn             INTEGER,
    descr          VARCHAR(255),
    CONSTRAINT pk_license PRIMARY KEY (id)
);

CREATE TABLE player(
    id         INTEGER NOT NULL,
    first_name VARCHAR(255),
    rating     INTEGER,
    CONSTRAINT pk_player PRIMARY KEY (id)
);

CREATE TABLE player_sport_school(
    player_id       INTEGER      NOT NULL,
    sport_school_id VARCHAR(255) NOT NULL,
    CONSTRAINT pk_player_sport_school PRIMARY KEY (player_id, sport_school_id)
);

CREATE TABLE referee(
    id         INTEGER NOT NULL,
    first_name VARCHAR(255),
    license_id BIGINT,
    CONSTRAINT pk_referee PRIMARY KEY (id)
);

CREATE TABLE sport_school(
    id    VARCHAR(255) NOT NULL,
    title VARCHAR(255),
    CONSTRAINT pk_sport_school PRIMARY KEY (id)
);

CREATE TABLE sport_school_rating(
    school_id VARCHAR(255) NOT NULL,
    rating    INTEGER      NOT NULL
);

